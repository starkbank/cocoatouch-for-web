// UIDatePicker.Mode. The cases are the strings the picker has always taken, so
// `datePickerMode = "time"` and `UIDatePicker.Mode.time` are the same value.
// countDownTimer is not here: a page has no control that draws it.
export const UIDatePickerMode = Object.freeze({
    time: "time",
    date: "date",
    dateAndTime: "dateAndTime",
    yearAndMonth: "yearAndMonth",
})
