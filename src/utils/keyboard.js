

export class Keyboard {

    static get enter() { return "keyboard:Enter" }

    static get space() { return "keyboard: " }

    static get escape() { return "keyboard:Escape" }

    static get arrowUp() { return "keyboard:ArrowUp" }

    static get arrowDown() { return "keyboard:ArrowDown" }

    static get command() { return "meta+" }

    static get control() { return "ctrl+" }

    static get shift() { return "shift+" }

    static get alt() { return "alt+" }

    static get option() { return "alt+" }

    static get k() { return "keyboard:k" }
}
