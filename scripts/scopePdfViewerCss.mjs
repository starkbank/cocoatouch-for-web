// Dev-time generator for styles/pdf_viewer.scoped.css, the pdf.js viewer
// stylesheet confined to a PDFView. pdfjs-dist/web/pdf_viewer.css styles
// unscoped names (.sidebar, .page, .dialog, .toggle-button) and :root, which
// restyles the host app on every page that imports PDFKit; here every selector
// is a descendant of `.ct-pdfview`, the class PDFView puts on its element.
//
//   node scripts/scopePdfViewerCss.mjs           writes styles/pdf_viewer.scoped.css
//   node scripts/scopePdfViewerCss.mjs --check   fails when the committed file is stale
//
// postcss is a devDependency: it runs here and in the drift test, never in an app.
import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"

const require = createRequire(import.meta.url)
const postcss = require("postcss")
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")

export const scope = ".ct-pdfview"
export const keyframePrefix = "ct-pdfview-"

const printOnly = /#printContainer|data-pdfjsprinting/
// The document itself is no part of a PDF view: :root wherever it stands, and html and body as type selectors.
const documentSelector = /:root(?![\w-])|(^|[\s>+~(,])(html|body)(?![\w-])/
const imageBase = "pdfjs-dist/web/"
const outputPath = path.join(root, "styles/pdf_viewer.scoped.css")


// `css` is pdf_viewer.css and `javascript` the text of the scripts that drive
// it, which say which custom properties pdf.js sets itself at run time.
export function scopePdfViewerCss({css, javascript}) {
    var tree = postcss.parse(css)
    var licence = tree.first && tree.first.type === "comment" ? tree.first.text : null
    tree.walkComments((comment) => comment.remove())
    var setFromScript = _variablesSetFromScript(javascript)
    var keyframes = _renameKeyframes(tree)

    tree.walkRules((rule) => {
        if (_isNested(rule)) { return }
        _scopeRule(rule, setFromScript)
    })
    tree.walkDecls((declaration) => {
        _rewriteAnimation(declaration, keyframes)
        _rewriteUrls(declaration)
    })
    _removeEmpty(tree)

    var header = "Generated by scripts/scopePdfViewerCss.mjs from pdfjs-dist/web/pdf_viewer.css: do not edit, run `npm run styles:pdfviewer`.\n * Every selector is a descendant of .ct-pdfview, the class PDFView puts on its element."
    if (licence !== null) { tree.prepend(postcss.comment({text: licence, raws: {left: " ", right: "\n "}})) }
    tree.prepend(postcss.comment({text: header, raws: {left: " ", right: "\n "}}))
    return tree.toString().replace(/\n{3,}/g, "\n\n").trimEnd() + "\n"
}

export function generateInstalled() {
    var base = path.join(root, "node_modules/pdfjs-dist")
    var javascript = ["web/pdf_viewer.mjs", "build/pdf.mjs"].map((file) => fs.readFileSync(path.join(base, file), "utf8")).join("\n")
    var css = fs.readFileSync(path.join(base, "web/pdf_viewer.css"), "utf8")
    return scopePdfViewerCss({css: css, javascript: javascript})
}


// A rule inside another rule, or inside a media block inside one, is relative
// to its parent: only the rules a document is matched against are scoped.
function _isNested(rule) {
    for (var parent = rule.parent; parent; parent = parent.parent) {
        if (parent.type === "rule") { return true }
        if (parent.type === "atrule" && /keyframes$/i.test(parent.name)) { return true }
    }
    return false
}

function _scopeRule(rule, setFromScript) {
    if (rule.selectors.some((selector) => selector.trim() === ":root") && rule.selectors.length === 1) {
        // The :root defaults become the view's own. A variable pdf.js sets on
        // the document stays there: a default on .ct-pdfview would shadow it.
        rule.walkDecls((declaration) => {
            if (setFromScript.has(declaration.prop)) { declaration.remove() }
        })
        rule.selector = scope
        return
    }
    var kept = rule.selectors.filter((selector) => !printOnly.test(selector) && !documentSelector.test(selector))
    if (kept.length === 0) {
        rule.remove()
        return
    }
    rule.selectors = kept.map((selector) => `${scope} ${selector.trim()}`)
}

function _variablesSetFromScript(javascript) {
    var names = new Set()
    for (var match of javascript.matchAll(/setProperty\(\s*["'`](--[\w-]+)/g)) { names.add(match[1]) }
    return names
}

function _renameKeyframes(tree) {
    var names = new Set()
    tree.walkAtRules(/keyframes$/i, (atRule) => {
        names.add(atRule.params.trim())
        atRule.params = keyframePrefix + atRule.params.trim()
    })
    return names
}

// animation and animation-name list the keyframes they run, among keywords
// and times; only a token that is a renamed keyframe's name changes.
function _rewriteAnimation(declaration, keyframes) {
    if (keyframes.size === 0 || !/^animation(-name)?$/i.test(declaration.prop)) { return }
    declaration.value = declaration.value.replace(/[^\s,]+/g, (token) => keyframes.has(token) ? keyframePrefix + token : token)
}

function _rewriteUrls(declaration) {
    if (!declaration.value.includes("url(")) { return }
    declaration.value = declaration.value.replace(/url\(\s*(["']?)([^)"']*)\1\s*\)/g, (whole, quote, target) => {
        if (target === "" || /^(data:|https?:|\/|#|var\()/i.test(target) || target.startsWith(imageBase)) { return whole }
        return `url(${quote}${path.posix.normalize(imageBase + target)}${quote})`
    })
}

// A block whose only content was removed goes too, with a media wrapper left empty.
function _removeEmpty(tree) {
    var removed = true
    while (removed) {
        removed = false
        tree.walk((node) => {
            if ((node.type === "rule" || node.type === "atrule") && node.nodes && node.nodes.length === 0 && !/^(font-face|page|layer)$/i.test(node.name || "")) {
                node.remove()
                removed = true
            }
        })
    }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    var generated = generateInstalled()
    if (process.argv.includes("--check")) {
        var current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : ""
        if (current !== generated) {
            console.error("styles/pdf_viewer.scoped.css is stale: run `npm run styles:pdfviewer`.")
            process.exit(1)
        }
        console.log("styles/pdf_viewer.scoped.css is current.")
    }
    if (!process.argv.includes("--check")) {
        fs.writeFileSync(outputPath, generated)
        console.log("wrote styles/pdf_viewer.scoped.css")
    }
}
